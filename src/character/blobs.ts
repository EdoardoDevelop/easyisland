// Roccia, Magma and Pietra: three blobs measured on Edoardo's character sheet
// (front views, about 120 px wide).
// Each measured blob is its outline (128 radii, like the Geco), a base colour
// and the patches of colour the sheet shows (stone faces, moss, rock plates and
// lava, highlights), traced from the picture and drawn as curves; the eyes are
// the sheet's big black ovals with a glint. Soft characters (see character.ts).
// Body-local coordinates: (0, 0) is the centre, `hw` the half-width, `hh` the
// half-height, y down, the base on y = hh. All numbers are in units of hw, hh.

import { rgba, type BodyLook, type Palette, type RGB, type SoftCharacter } from "./character";

interface Measured {
  /** The outline: its distance from the centre every 2.8125°, clockwise from the right. */
  radii: number[];
  /** The colours of the patches (0–255). */
  colors: number[][];
  /** The colour under everything. */
  base: number;
  /** A patch: colour, 1 if it sits outside the outline (a sprout), then its loops (outline, holes). */
  layers: (number | number[])[][];
  /** The dark line round the body (0–255). */
  outline: number[];
}

interface Setup {
  id: string;
  name: string;
  /** The sheet's palette for this character; `body` is its colour. */
  palette: { light: RGB; body: RGB; edge: RGB };
  size: { hw: number; hh: number };
  face: { eyeSpread: number; eyeDrop: number; eyeRadius: number; blushX: number; blushY: number };
  /** Drawn over the patches, inside the outline (the leaf's veins), with the tinted colours. */
  inside?: (x: CanvasRenderingContext2D, hw: number, hh: number, col: (c: number[]) => string) => void;
  /** Drawn last, over the outline (the leaf's curl), with the character's tinted colours. */
  front?: (x: CanvasRenderingContext2D, hw: number, hh: number, col: (c: number[]) => string) => void;
  /** A smooth base from the top left to the bottom right (0–255) instead of the flat base colour. */
  shade?: number[][];
  /** All green (a leaf): the theme and the states tint its greens too. */
  tintGreens?: boolean;
  /** The eye: width / height, and the glint (x, y as a fraction of the eye, radius as a fraction of its width). */
  eye: { ratio: number; glint: [number, number, number] };
}

/** The outline radius in direction `a` (Catmull-Rom through the radii, wrapping round). */
function radius(r: number[], a: number): number {
  const n = r.length;
  const f = ((((a / (Math.PI * 2)) * n) % n) + n) % n;
  const i = Math.floor(f);
  const t = f - i;
  const p0 = r[(i - 1 + n) % n], p1 = r[i], p2 = r[(i + 1) % n], p3 = r[(i + 2) % n];
  return 0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t +
    (3 * p1 - p0 - 3 * p2 + p3) * t * t * t);
}

/** A closed loop through the points, rounded with curves through their midpoints. */
function addLoop(p: Path2D, pts: number[], hw: number, hh: number) {
  const n = pts.length / 2;
  const at = (i: number): [number, number] => [pts[(i % n) * 2] * hw, pts[(i % n) * 2 + 1] * hh];
  const mid = (i: number): [number, number] => {
    const [ax, ay] = at(i), [bx, by] = at(i + 1);
    return [(ax + bx) / 2, (ay + by) / 2];
  };
  p.moveTo(...mid(0));
  for (let i = 1; i <= n; i++) p.quadraticCurveTo(...at(i), ...mid(i));
  p.closePath();
}

/** Moss and leaves keep their green whatever the theme; the rest follows it. */
function isGreen(c: number[]): boolean {
  return c[1] > c[0] + 20 && c[1] > c[2] + 20;
}

/** A colour moved by `dx` (the theme or the state), kept in range. */
function shifted(c: RGB, dx: number[]): RGB {
  return [
    Math.min(1, Math.max(0, c[0] + dx[0])),
    Math.min(1, Math.max(0, c[1] + dx[1])),
    Math.min(1, Math.max(0, c[2] + dx[2])),
  ];
}

/** How far the body has turned into the file box (the engine passes gloss = 1 − morph × 0.6). */
function morphOf(look: BodyLook): number {
  return Math.min(1, Math.max(0, (1 - (look.gloss ?? 1)) / 0.6));
}

function makeMeasured(d: Measured, s: Setup): SoftCharacter {
  // The measured outline, smoothed: the picture's pixels would leave it ragged.
  let radii = d.radii;
  for (let k = 0; k < 4; k++) radii = radii.map((v, i) => (radii[(i - 1 + radii.length) % radii.length] + 2 * v + radii[(i + 1) % radii.length]) / 4);
  // The patches' paths for the last size drawn: rebuilt only when the size changes.
  let cache: { key: string; inside: [number, Path2D][]; outside: [number, Path2D][] } | null = null;
  const paths = (hw: number, hh: number) => {
    const key = `${hw.toFixed(2)},${hh.toFixed(2)}`;
    if (cache?.key === key) return cache;
    const inside: [number, Path2D][] = [], outside: [number, Path2D][] = [];
    for (const l of d.layers) {
      const p = new Path2D();
      for (const loop of l.slice(2) as number[][]) addLoop(p, loop, hw, hh);
      (l[1] === 1 ? outside : inside).push([l[0] as number, p]);
    }
    cache = { key, inside, outside };
    return cache;
  };

  return {
    kind: "soft",
    id: s.id,
    name: s.name,
    color: s.palette.body,
    aspect: s.size.hw / s.size.hh,
    wearsIntegrationColor: true,
    size: s.size,
    face: s.face,
    wobbles: true,
    point: (ca, sa, hw, hh) => {
      const r = radius(radii, Math.atan2(sa, ca));
      return { x: ca * r * hw, y: sa * r * hh };
    },
    palette: (base: RGB): Palette => {
      // The sheet's palette, moved by however far the theme or the state moves the body colour.
      const dx = base.map((v, i) => v - s.palette.body[i]);
      return { light: shifted(s.palette.light, dx), body: base, edge: shifted(s.palette.edge, dx) };
    },
    drawBody: (x, body, hw, hh, look) => {
      const morph = morphOf(look);
      // The theme or the state moves every colour by as much as the body.
      const dx = look.palette.body.map((v, i) => v - s.palette.body[i]);
      const col = (c: number[]) => {
        const rgb: RGB = [c[0] / 255, c[1] / 255, c[2] / 255];
        return rgba(isGreen(c) && !s.tintGreens ? rgb : shifted(rgb, dx));
      };
      const { inside, outside } = paths(hw, hh);

      if (s.shade) {
        const g = x.createLinearGradient(-hw * 0.7, -hh, hw * 0.6, hh);
        s.shade.forEach((c, i) => g.addColorStop(i / (s.shade!.length - 1), col(c)));
        x.fillStyle = g;
      } else {
        x.fillStyle = col(d.colors[d.base]);
      }
      x.fill(body);
      x.save();
      x.clip(body);
      // Each patch is also stroked in its own colour, closing the hairline gaps
      // that rounding the traced shapes leaves between neighbours.
      x.lineWidth = hh * 0.03;
      x.lineJoin = "round";
      for (const [c, p] of inside) {
        x.fillStyle = x.strokeStyle = col(d.colors[c]);
        x.fill(p, "evenodd");
        x.stroke(p);
      }
      s.inside?.(x, hw, hh, col);
      x.restore();
      x.strokeStyle = col(d.outline);
      x.lineWidth = Math.max(0.7, hh * 0.03);
      x.lineJoin = "round";
      x.stroke(body);
      if ((outside.length || s.front) && morph < 0.98) {
        x.save();
        x.globalAlpha = 1 - morph;
        for (const [c, p] of outside) {
          x.fillStyle = col(d.colors[c]);
          x.fill(p, "evenodd");
        }
        s.front?.(x, hw, hh, col);
        x.restore();
      }
    },
    drawEye: (x, r, open) => {
      // The sheet's big black oval, a little lighter low down, with its glint.
      const ry = (r / Math.cos(s.face.eyeDrop)) * Math.max(0.1, open);
      const rx = (r * s.eye.ratio) / Math.cos(s.face.eyeSpread);
      const g = x.createLinearGradient(0, -ry, 0, ry);
      g.addColorStop(0, "rgb(8,8,12)");
      g.addColorStop(0.6, "rgb(14,14,20)");
      g.addColorStop(1, "rgb(52,54,64)");
      x.fillStyle = g;
      x.beginPath();
      x.ellipse(0, 0, rx, ry, 0, 0, Math.PI * 2);
      x.fill();
      if (open > 0.45) {
        const [gx, gy, gr] = s.eye.glint;
        x.fillStyle = "rgba(255,255,255,0.96)";
        x.beginPath();
        x.ellipse(gx * rx, gy * ry, gr * rx, gr * rx * Math.min(1, open), 0, 0, Math.PI * 2);
        x.fill();
      }
    },
  };
}

